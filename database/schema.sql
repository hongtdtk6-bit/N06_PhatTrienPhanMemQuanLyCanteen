DROP DATABASE IF EXISTS canteen_db;
CREATE DATABASE canteen_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE canteen_db;

CREATE TABLE users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(120) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL UNIQUE,
 password_hash VARCHAR(64) NOT NULL,
 role ENUM('CUSTOMER','STAFF','MANAGER') NOT NULL DEFAULT 'CUSTOMER',
 status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
 birth_date DATE NULL,
 address VARCHAR(255),
 avatar_url VARCHAR(255),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE goods (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 code VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 group_name VARCHAR(100),
 unit VARCHAR(30) NOT NULL,
 quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
 reserved_quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
 min_quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
 supplier VARCHAR(150),
 status ENUM('ACTIVE','STOPPED') NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE foods (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(150) NOT NULL,
 description VARCHAR(500),
 category VARCHAR(100),
 price DECIMAL(12,2) NOT NULL,
 image_url VARCHAR(255),
 status ENUM('AVAILABLE','STOPPED') NOT NULL DEFAULT 'AVAILABLE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE toppings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(150) NOT NULL,
 price DECIMAL(12,2) NOT NULL DEFAULT 0,
 status ENUM('AVAILABLE','STOPPED') NOT NULL DEFAULT 'AVAILABLE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE food_ingredients (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 food_id BIGINT NOT NULL,
 good_id BIGINT NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 UNIQUE(food_id, good_id),
 FOREIGN KEY(food_id) REFERENCES foods(id) ON DELETE CASCADE,
 FOREIGN KEY(good_id) REFERENCES goods(id)
);

CREATE TABLE topping_ingredients (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 topping_id BIGINT NOT NULL,
 good_id BIGINT NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 UNIQUE(topping_id, good_id),
 FOREIGN KEY(topping_id) REFERENCES toppings(id) ON DELETE CASCADE,
 FOREIGN KEY(good_id) REFERENCES goods(id)
);

CREATE TABLE food_toppings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 food_id BIGINT NOT NULL,
 topping_id BIGINT NOT NULL,
 UNIQUE(food_id,topping_id),
 FOREIGN KEY(food_id) REFERENCES foods(id) ON DELETE CASCADE,
 FOREIGN KEY(topping_id) REFERENCES toppings(id) ON DELETE CASCADE
);

CREATE TABLE menus (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(150) NOT NULL,
 menu_type VARCHAR(50) NOT NULL,
 start_time DATETIME NOT NULL,
 end_time DATETIME NOT NULL,
 status ENUM('DRAFT','PUBLISHED','CLOSED') NOT NULL DEFAULT 'DRAFT',
 created_by BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE menu_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 menu_id BIGINT NOT NULL,
 food_id BIGINT NOT NULL,
 UNIQUE(menu_id,food_id),
 FOREIGN KEY(menu_id) REFERENCES menus(id) ON DELETE CASCADE,
 FOREIGN KEY(food_id) REFERENCES foods(id)
);

CREATE TABLE inventory_transactions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 good_id BIGINT NOT NULL,
 transaction_type ENUM('IMPORT','RESERVE','RELEASE','USE','ADJUST') NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 reference_type VARCHAR(50),
 reference_id BIGINT,
 note VARCHAR(255),
 created_by BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(good_id) REFERENCES goods(id),
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE purchase_receipts (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 receipt_code VARCHAR(50) NOT NULL UNIQUE,
 supplier VARCHAR(150),
 receipt_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status ENUM('DRAFT','CONFIRMED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
 total_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
 created_by BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE purchase_receipt_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 receipt_id BIGINT NOT NULL,
 good_id BIGINT NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(receipt_id) REFERENCES purchase_receipts(id) ON DELETE CASCADE,
 FOREIGN KEY(good_id) REFERENCES goods(id)
);

CREATE TABLE orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_code VARCHAR(50) NOT NULL UNIQUE,
 customer_id BIGINT NOT NULL,
 total_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
 status ENUM('PENDING','CONFIRMED','PREPARING','READY','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
 payment_status ENUM('UNPAID','PAID','REFUNDED','CANCELLED') NOT NULL DEFAULT 'UNPAID',
 note VARCHAR(500),
 pickup_info VARCHAR(255),
 cancel_reason VARCHAR(255),
 cancelled_at DATETIME NULL,
 completed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id)
);

CREATE TABLE order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL,
 food_id BIGINT NOT NULL,
 quantity INT NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,
 subtotal DECIMAL(14,2) NOT NULL,
 note VARCHAR(255),
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(food_id) REFERENCES foods(id)
);

CREATE TABLE order_item_toppings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_item_id BIGINT NOT NULL,
 topping_id BIGINT NOT NULL,
 quantity INT NOT NULL DEFAULT 1,
 unit_price DECIMAL(12,2) NOT NULL,
 subtotal DECIMAL(14,2) NOT NULL,
 FOREIGN KEY(order_item_id) REFERENCES order_items(id) ON DELETE CASCADE,
 FOREIGN KEY(topping_id) REFERENCES toppings(id)
);

CREATE TABLE order_status_history (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL,
 old_status VARCHAR(30),
 new_status VARCHAR(30) NOT NULL,
 reason VARCHAR(255),
 changed_by BIGINT,
 changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(changed_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE payments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL UNIQUE,
 method ENUM('CASH','QR','BANK_TRANSFER') NOT NULL,
 amount DECIMAL(14,2) NOT NULL,
 status ENUM('PENDING','PAID','REFUNDED','CANCELLED') NOT NULL DEFAULT 'PENDING',
 transaction_code VARCHAR(100),
 confirmed_by BIGINT,
 paid_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(confirmed_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_food_status ON foods(status);
CREATE INDEX idx_goods_status ON goods(status);
CREATE INDEX idx_goods_code ON goods(code);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_created_at ON orders(created_at);
CREATE INDEX idx_payment_status ON payments(status);
CREATE INDEX idx_inventory_good ON inventory_transactions(good_id,created_at);
